<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use App\Models\Court;
use App\Models\Courtroom;

class CourtroomSeeder extends Seeder
{
    public function run(): void
    {
        // جلب جميع المحاكم من قاعدة البيانات
        $courts = Court::all();

        foreach ($courts as $court) {
            $rooms = [];

            // 1. إذا كانت محكمة ابتدائية (Level ID = 1)
            if ($court->level_id == 1) {
                $rooms = [
                    'القسم المدني',
                    'قسم الجنح',
                    'قسم المخالفات',
                    'القسم الاستعجالي',
                    'قسم شؤون الأسرة',
                    'قسم الأحداث',
                    'القسم الاجتماعي',
                    'القسم العقاري',
                    'القسم البحري',
                    'القسم التجاري',
                ];
            } 
            // 2. إذا كان مجلساً قضائياً (Level ID = 2)
            elseif ($court->level_id == 2) {
                $rooms = [
                    'الغرفة المدنية',
                    'الغرفة الجزائية',
                    'غرفة الاتهام',
                    'الغرفة الاستعجالية',
                    'غرفة شؤون الأسرة',
                    'غرفة الأحداث',
                    'الغرفة الاجتماعية',
                    'الغرفة العقارية',
                    'الغرفة البحرية',
                    'الغرفة التجارية',
                    'محكمة الجنايات الابتدائية',
                    'محكمة الجنايات الاستئنافية',
                ];
            } 
            // 3. إذا كانت المحكمة العليا (Level ID = 3)
            elseif ($court->level_id == 3) {
                $rooms = [
                    'الغرفة المدنية',
                    'الغرفة العقارية',
                    'غرفة شؤون الأسرة والمواريث',
                    'الغرفة التجارية والبحرية',
                    'الغرفة الاجتماعية',
                    'الغرفة الجنائية',
                    'غرفة الجنح والمخالفات',
                    'غرفة الأحوال الشخصية',
                ];
            }

            // عملية الإدخال أو التحديث لكل غرفة/قسم تابع للمحكمة الحالية
            foreach ($rooms as $roomName) {
                Courtroom::updateOrCreate([
                    'court_id' => $court->id,
                    'name'     => $roomName
                ]);
            }
        }
    }
}